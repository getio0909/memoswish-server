pub(super) fn normalize(path: &str) -> &'static str {
    if path.starts_with("/extensions/") || path == "/extensions" {
        return "extensions";
    }
    if path == "/v1/{*rest}" {
        return "fallback";
    }
    ROUTES.iter().copied().find(|route| *route == path).unwrap_or("unmatched")
}
